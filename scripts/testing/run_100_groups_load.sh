#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT_DIR"

# Examples:
#   scripts/testing/run_100_groups_load.sh
#   GROUP_COUNT=100 PER_GROUP_PER_MIN=20 DURATION=2h TEST_TIMEOUT=150m HISTORY=1000000 SHARDS=8 scripts/testing/run_100_groups_load.sh
#   OUTBOUND_RTT_MS=300 OUTBOUND_RATE_LIMIT_EVERY=5 OUTBOUND_BENCH_TIME=10m scripts/testing/run_100_groups_load.sh

GROUP_COUNT="${GROUP_COUNT:-100}"
PER_GROUP_PER_MIN="${PER_GROUP_PER_MIN:-10}"
DURATION="${DURATION:-2m}"
TEST_TIMEOUT="${TEST_TIMEOUT:-10m}"
CONCURRENCY="${CONCURRENCY:-32}"
HISTORY="${HISTORY:-0}"
SHARDS="${SHARDS:-1}"
PACE="${PACE:-1}"

OUTBOUND_WORKERS="${OUTBOUND_WORKERS:-4}"
OUTBOUND_DEPTH="${OUTBOUND_DEPTH:-4096}"
OUTBOUND_RTT_MS="${OUTBOUND_RTT_MS:-200}"
OUTBOUND_MODE="${OUTBOUND_MODE:-rate_limit}"
OUTBOUND_RATE_LIMIT_EVERY="${OUTBOUND_RATE_LIMIT_EVERY:-10}"
OUTBOUND_BENCH_TIME="${OUTBOUND_BENCH_TIME:-30s}"

echo "== Ledger load: groups=${GROUP_COUNT} per_group_per_min=${PER_GROUP_PER_MIN} duration=${DURATION} concurrency=${CONCURRENCY} history=${HISTORY} shards=${SHARDS} pace=${PACE}"
RUN_LEDGER_LOAD_TEST=1 \
LEDGER_LOAD_GROUPS="$GROUP_COUNT" \
LEDGER_LOAD_PER_GROUP_PER_MIN="$PER_GROUP_PER_MIN" \
LEDGER_LOAD_DURATION="$DURATION" \
LEDGER_LOAD_CONCURRENCY="$CONCURRENCY" \
LEDGER_LOAD_HISTORY="$HISTORY" \
LEDGER_LOAD_SHARDS="$SHARDS" \
LEDGER_LOAD_PACE="$PACE" \
go test ./internal/db -run '^TestLedger100GroupsHighFrequencyLoad$' -count=1 -timeout "$TEST_TIMEOUT"

echo "== Outbound bench: groups=${GROUP_COUNT} per_group_per_min=${PER_GROUP_PER_MIN} rtt_ms=${OUTBOUND_RTT_MS} workers=${OUTBOUND_WORKERS} depth=${OUTBOUND_DEPTH} mode=${OUTBOUND_MODE} rate_limit_every=${OUTBOUND_RATE_LIMIT_EVERY}"
OUTBOUND_BENCH_GROUPS="$GROUP_COUNT" \
OUTBOUND_BENCH_PER_GROUP_PER_MIN="$PER_GROUP_PER_MIN" \
OUTBOUND_BENCH_WORKERS="$OUTBOUND_WORKERS" \
OUTBOUND_BENCH_DEPTH="$OUTBOUND_DEPTH" \
OUTBOUND_BENCH_RTT_MS="$OUTBOUND_RTT_MS" \
OUTBOUND_BENCH_MODE="$OUTBOUND_MODE" \
OUTBOUND_BENCH_RATE_LIMIT_EVERY="$OUTBOUND_RATE_LIMIT_EVERY" \
go test ./internal/bot -bench '^BenchmarkOutboundDispatch$' -benchmem -run '^$' -benchtime="$OUTBOUND_BENCH_TIME" -count=1
